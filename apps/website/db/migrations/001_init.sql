-- PlainClick licensing schema v1. PostgreSQL 15+.
-- Principles: provider IDs are unique (idempotency), one licence per purchase, licence keys never stored in plaintext.

CREATE TABLE IF NOT EXISTS schema_migrations (
  version     TEXT PRIMARY KEY,
  applied_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Every webhook we accept, recorded before processing. The unique key makes retries/duplicates no-ops.
CREATE TABLE IF NOT EXISTS webhook_events (
  id               BIGSERIAL PRIMARY KEY,
  provider         TEXT NOT NULL,
  event_id         TEXT NOT NULL,
  event_type       TEXT NOT NULL,
  occurred_at      TIMESTAMPTZ,
  received_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  processed_at     TIMESTAMPTZ,
  outcome          TEXT,
  UNIQUE (provider, event_id)
);

-- One row per provider transaction. A refund can arrive before the payment (out of order): the row is created
-- by whichever event comes first.
CREATE TABLE IF NOT EXISTS purchases (
  id                    BIGSERIAL PRIMARY KEY,
  provider              TEXT NOT NULL,
  provider_txn_id       TEXT NOT NULL,
  provider_customer_id  TEXT,
  customer_email        TEXT,
  price_id              TEXT,
  currency              TEXT,
  subtotal_minor        BIGINT,
  status                TEXT NOT NULL CHECK (status IN ('pending', 'paid', 'needs_review', 'refunded')),
  review_reason         TEXT,
  paid_at               TIMESTAMPTZ,
  refunded_at           TIMESTAMPTZ,
  created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (provider, provider_txn_id)
);
CREATE INDEX IF NOT EXISTS purchases_email_idx ON purchases (lower(customer_email));

CREATE TABLE IF NOT EXISTS licences (
  id               BIGSERIAL PRIMARY KEY,
  purchase_id      BIGINT NOT NULL UNIQUE REFERENCES purchases(id),
  public_id        TEXT NOT NULL UNIQUE,      -- random, non-sequential id placed in entitlements
  key_lookup       TEXT NOT NULL UNIQUE,      -- HMAC-SHA256(pepper, normalised key), hex
  key_ciphertext   TEXT NOT NULL,             -- AES-256-GCM, for recovery emails only
  major_version    INT NOT NULL DEFAULT 1,
  max_activations  INT NOT NULL DEFAULT 2,
  status           TEXT NOT NULL CHECK (status IN ('active', 'revoked')) DEFAULT 'active',
  revoked_reason   TEXT,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  revoked_at       TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS activations (
  id               BIGSERIAL PRIMARY KEY,
  licence_id       BIGINT NOT NULL REFERENCES licences(id),
  installation_id  TEXT NOT NULL,             -- random UUID generated by the app; not a hardware identifier
  device_label     TEXT,                      -- optional, user-visible name the app sends (e.g. "MacBook Air")
  app_version      TEXT,
  activated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_seen_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  deactivated_at   TIMESTAMPTZ,
  deactivated_by   TEXT
);
-- At most one live activation per installation per licence.
CREATE UNIQUE INDEX IF NOT EXISTS activations_live_unique
  ON activations (licence_id, installation_id) WHERE deactivated_at IS NULL;

CREATE TABLE IF NOT EXISTS recovery_tokens (
  id           BIGSERIAL PRIMARY KEY,
  token_hash   TEXT NOT NULL UNIQUE,          -- SHA-256 of the token; the token itself is only in the email
  email        TEXT NOT NULL,
  expires_at   TIMESTAMPTZ NOT NULL,
  used_at      TIMESTAMPTZ,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Durable outbox. A paid customer's licence email survives email-provider outages.
CREATE TABLE IF NOT EXISTS email_jobs (
  id                 BIGSERIAL PRIMARY KEY,
  kind               TEXT NOT NULL CHECK (kind IN ('licence_delivery', 'recovery_link')),
  purchase_id        BIGINT REFERENCES purchases(id),
  to_email           TEXT,                    -- may be resolved later from the provider's customer record
  payload_ciphertext TEXT NOT NULL,           -- encrypted JSON (contains the licence key or recovery link)
  status             TEXT NOT NULL CHECK (status IN ('pending', 'sent', 'failed')) DEFAULT 'pending',
  attempts           INT NOT NULL DEFAULT 0,
  next_attempt_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_error         TEXT,
  created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  sent_at            TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS email_jobs_due_idx ON email_jobs (next_attempt_at) WHERE status = 'pending';

-- Fixed-window rate limiting without extra infrastructure.
CREATE TABLE IF NOT EXISTS rate_limits (
  bucket        TEXT NOT NULL,
  window_start  TIMESTAMPTZ NOT NULL,
  count         INT NOT NULL DEFAULT 0,
  PRIMARY KEY (bucket, window_start)
);

CREATE TABLE IF NOT EXISTS waitlist (
  id            BIGSERIAL PRIMARY KEY,
  email         TEXT NOT NULL,
  consented_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (email)
);
